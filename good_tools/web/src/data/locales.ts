export type LangMode = 'ko' | 'en' | 'ja' | 'zh' | 'zh-TW' | 'es' | 'de' | 'fr' | 'pt' | 'vi';

export interface LanguageOption {
  code: LangMode;
  short: string;
  nativeName: string;
  flag: string;
}

