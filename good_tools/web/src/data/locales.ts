export const VALID_LANGS = new Set<string>(LANGUAGE_OPTIONS.map((l) => l.code));

export function isValidLang(value: unknown): value is LangMode {
  return typeof value === 'string' && VALID_LANGS.has(value);
}

export function getLanguageOption(lang: LangMode): LanguageOption {
  return LANGUAGE_OPTIONS.find((l) => l.code === lang) || LANGUAGE_OPTIONS[0];
}

