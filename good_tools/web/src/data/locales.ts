export function translatePhrase(lang: LangMode, korean: string, english: string): string {
  if (lang === 'ko') return korean;
  if (lang === 'en') return english;
  return COMMON_PHRASES[lang]?.[english] ?? english;
}

export function getToolName(tool: ToolMeta, lang: LangMode): string {
  if (lang === 'ko') return tool.name;
  if (lang === 'en') return tool.nameEn || tool.name;
  return TOOL_NAMES_I18N[lang]?.[tool.id] || tool.nameEn || tool.name;
}

export function getToolDesc(tool: ToolMeta, lang: LangMode): string {
  if (lang === 'ko') return tool.shortDesc;
  return tool.shortDescEn || tool.shortDesc;
}
